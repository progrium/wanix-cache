// SyntheticDir is the root directory that holds synthetic files:
// /.cache/usage, /.cache/stats.
const SyntheticDir = ".cache"

// SyntheticFunc generates a synthetic file's bytes.
type SyntheticFunc func(ctx context.Context) ([]byte, error)

// Synthetic files have inode numbers with bit 60 set and their position in
// name order below it. Real inodes are SQLite rowids, h9index files use
// bits 63 and 62, and virtual view directories bit 61, so these collide
// with none of them.
const synthBit = 1 << 60

func isSynth(ino uint64) bool { return ino&^(synthBit-1) == synthBit }

// synthFresh is how long a generated file is reused, so the lookup, stat
// and open of one `cat` see the same bytes and generate them once.
const synthFresh = 2 * time.Second

type synthSnap struct {
	b  []byte
	at time.Time
}

// InitSynthetic creates /.cache, so it lists in the root, and remembers it.
// Call it once before serving when Synthetic is set.
func (f *FS) InitSynthetic(ctx context.Context) error {
	if len(f.Synthetic) == 0 {
		return nil
	}
	tx, err := f.Meta.Begin(ctx)
	if err != nil {
		return err
	}
	ino, err := tx.MkdirAll("/" + SyntheticDir)
	if err != nil {
		tx.Rollback()
		return err
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	f.synthMu.Lock()
	f.synthDir = ino
	f.synthSnaps = map[string]synthSnap{}
	f.synthMu.Unlock()
	return nil
}

func (f *FS) synthNames() []string {
	names := make([]string, 0, len(f.Synthetic))
	for n := range f.Synthetic {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

func (f *FS) isSynthDir(dir uint64) bool {
	if len(f.Synthetic) == 0 {
		return false
	}
	f.synthMu.Lock()
	defer f.synthMu.Unlock()
	return f.synthDir != 0 && dir == f.synthDir
}

// synthInode generates (or reuses) the synthetic file name and returns its
// inode.
func (f *FS) synthInode(ctx context.Context, name string, generate bool) (meta.Inode, error) {
	fn, ok := f.Synthetic[name]
	if !ok {
		return meta.Inode{}, meta.ErrNotExist
	}
	pos := sort.SearchStrings(f.synthNames(), name)
	f.synthMu.Lock()
	s, have := f.synthSnaps[name]
	f.synthMu.Unlock()
	if generate && (!have || time.Since(s.at) > synthFresh) {
		b, err := fn(ctx)
		if err != nil {
			return meta.Inode{}, err
		}
		s = synthSnap{b: b, at: time.Now()}
		f.synthMu.Lock()
		f.synthSnaps[name] = s
		f.synthMu.Unlock()
	}
	mtime := s.at
	if mtime.IsZero() {
		mtime = time.Now()
	}
	return meta.Inode{Ino: synthBit | uint64(pos+1), Kind: meta.KindFile, Mode: 0o444,
		Size: int64(len(s.b)), Mtime: mtime, Parent: f.synthDir}, nil
}

// synthLookup resolves name in dir if dir is /.cache and name is a
// synthetic file.
func (f *FS) synthLookup(ctx context.Context, dir uint64, name string) (meta.Inode, bool, error) {
	if !f.isSynthDir(dir) {
		return meta.Inode{}, false, nil
	}
	if _, ok := f.Synthetic[name]; !ok {
		return meta.Inode{}, false, nil
	}
	in, err := f.synthInode(ctx, name, true)
	return in, true, err
}

// synthEntries lists /.cache's synthetic files whose names sort after
// after. Sizes are those of the last generation (0 before the first).
func (f *FS) synthEntries(ctx context.Context, after string) []meta.Dirent {
	var out []meta.Dirent
	for _, name := range f.synthNames() {
		if name <= after {
			continue
		}
		in, err := f.synthInode(ctx, name, false)
		if err == nil {
			out = append(out, meta.Dirent{Name: name, Inode: in})
		}
	}
	return out
}

// synthOpen returns the bytes of synthetic inode ino, as generated by the
// lookup that found it (or freshly, if that was too long ago).
func (f *FS) synthOpen(ctx context.Context, ino uint64) (cas.File, error) {
	names := f.synthNames()
	pos := int(ino&(synthBit-1)) - 1
	if pos < 0 || pos >= len(names) {
		return nil, meta.ErrNotExist
	}
	if _, err := f.synthInode(ctx, names[pos], true); err != nil {
		return nil, err
	}
	f.synthMu.Lock()
	b := f.synthSnaps[names[pos]].b
	f.synthMu.Unlock()
	return bytesFile{bytes.NewReader(b)}, nil
}

// synthReaddir is Readdir for /.cache over 9P2000.L: the directory has no
// real entries, only the synthetic files, at offsets 1..n.
func (n *lnode) synthReaddir(ctx context.Context, offset uint64, count uint32) (p9.Dirents, error) {
	const direntFixed = 13 + 8 + 1 + 2
	var out p9.Dirents
	size := 0
	for i, de := range n.fs.synthEntries(ctx, "") {
		if uint64(i) < offset {
			continue
		}
		size += direntFixed + len(de.Name)
		if size > int(count) {
			break
		}
		q := lqid(de.Inode)
		out = append(out, p9.Dirent{QID: q, Type: q.Type, Name: de.Name, Offset: uint64(i) + 1})
	}
	return out, nil
}

func synthEntriesNineP(des []meta.Dirent) []ninep.Entry {
	out := make([]ninep.Entry, 0, len(des))
	for _, de := range des {
		out = append(out, ninep.Entry{Name: de.Name, Node: node(de.Inode)})
	}
	return out
}
