// fixture entries: "dir/" is a directory, "path" -> "content" a file,
// "->target" a symlink, "=>target" a hard link.
type fixtureEntry struct{ name, value string }

var fixtureTime = time.Unix(1_700_000_000, 0)

func gz(b []byte) []byte {
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	zw.Write(b)
	zw.Close()
	return buf.Bytes()
}

// tarBytes builds a tar; terminated adds the end-of-archive blocks, which
// apk strips from the signature and control streams.
func tarBytes(ents []fixtureEntry, terminated bool) []byte {
	var buf bytes.Buffer
	tw := tar.NewWriter(&buf)
	for _, e := range ents {
		h := &tar.Header{Name: e.name, ModTime: fixtureTime, Mode: 0o644, Format: tar.FormatPAX}
		switch {
		case strings.HasSuffix(e.name, "/"):
			h.Typeflag, h.Mode = tar.TypeDir, 0o755
		case strings.HasPrefix(e.value, "->"):
			h.Typeflag, h.Linkname, h.Mode = tar.TypeSymlink, e.value[2:], 0o777
		case strings.HasPrefix(e.value, "=>"):
			h.Typeflag, h.Linkname = tar.TypeLink, e.value[2:]
		default:
			h.Typeflag, h.Size = tar.TypeReg, int64(len(e.value))
			if strings.Contains(e.name, "bin/") {
				h.Mode = 0o755
			}
		}
		if err := tw.WriteHeader(h); err != nil {
			panic(err)
		}
		if h.Typeflag == tar.TypeReg {
			tw.Write([]byte(e.value))
		}
	}
	if terminated {
		tw.Close()
	} else {
		tw.Flush()
	}
	return buf.Bytes()
}

type fixturePkg struct {
	name, version, arch string
	files               []fixtureEntry
	unsigned            bool
	apk                 []byte
	checksum            string
	installed           int64
}

func (p *fixturePkg) build() *fixturePkg {
	data := gz(tarBytes(p.files, true))
	dh := sha256.Sum256(data)
	for _, f := range p.files {
		if !strings.HasSuffix(f.name, "/") && !strings.HasPrefix(f.value, "->") && !strings.HasPrefix(f.value, "=>") {
			p.installed += int64(len(f.value))
		}
	}
	pkginfo := fmt.Sprintf("# Generated by test\npkgname = %s\npkgver = %s\narch = %s\nsize = %d\ndatahash = %s\n",
		p.name, p.version, p.arch, p.installed, hex.EncodeToString(dh[:]))
	control := gz(tarBytes([]fixtureEntry{
		{".PKGINFO", pkginfo},
		{".post-install", "#!/bin/sh\necho must not run\n"},
	}, false))
	cs := sha1.Sum(control)
	p.checksum = Checksum(cs[:])
	var apk []byte
	if !p.unsigned {
		apk = append(apk, gz(tarBytes([]fixtureEntry{{".SIGN.RSA.test.rsa.pub", "not a real signature"}}, false))...)
	}
	apk = append(apk, control...)
	apk = append(apk, data...)
	p.apk = apk
	return p
}

func (p *fixturePkg) nv() string { return p.name + "-" + p.version }

func (p *fixturePkg) sha1hex() string {
	b, _ := ParseChecksum(p.checksum)
	return hex.EncodeToString(b)
}

func buildIndex(pkgs ...*fixturePkg) []byte {
	var idx strings.Builder
	for _, p := range pkgs {
		fmt.Fprintf(&idx, "C:%s\nP:%s\nV:%s\nA:%s\nS:%d\nI:%d\nT:test package\no:%s\nt:%d\n\n",
			p.checksum, p.name, p.version, p.arch, len(p.apk), p.installed, p.name, fixtureTime.Unix())
	}
	sig := gz(tarBytes([]fixtureEntry{{".SIGN.RSA.test.rsa.pub", "sig"}}, false))
	body := gz(tarBytes([]fixtureEntry{{"DESCRIPTION", "v3.20.0"}, {"APKINDEX", idx.String()}}, true))
	return append(sig, body...)
}

// upstream is a fake Alpine mirror with request counters.
type upstream struct {
	mu       sync.Mutex
	files    map[string][]byte
	gets     map[string]int
	notMod   int
	down     bool
	override map[string][]byte // served instead of files, e.g. a corrupted .apk
}

func newUpstream() *upstream {
	return &upstream{files: map[string][]byte{}, gets: map[string]int{}, override: map[string][]byte{}}
}

func (u *upstream) set(path string, b []byte) {
	u.mu.Lock()
	u.files[path] = b
	u.mu.Unlock()
}

func (u *upstream) count(path string) int {
	u.mu.Lock()
	defer u.mu.Unlock()
	return u.gets[path]
}

func (u *upstream) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	u.mu.Lock()
	if u.down {
		u.mu.Unlock()
		http.Error(w, "down", http.StatusServiceUnavailable)
		return
	}
	u.gets[r.URL.Path]++
	b, ok := u.override[r.URL.Path]
	if !ok {
		b, ok = u.files[r.URL.Path]
	}
	u.mu.Unlock()
	if !ok {
		http.NotFound(w, r)
		return
	}
	sum := sha256.Sum256(b)
	etag := `"up-` + hex.EncodeToString(sum[:8]) + `"`
	if r.Header.Get("If-None-Match") == etag {
		u.mu.Lock()
		u.notMod++
		u.mu.Unlock()
		w.WriteHeader(http.StatusNotModified)
		return
	}
	w.Header().Set("ETag", etag)
	w.Write(b)
}
